// Bundles public-domain books into bite-sized JSON for the reading feature.
// Usage: npx tsx scripts/make-books.ts <dir-with-gutenberg-txt-files>
// Texts come from Project Gutenberg (mirrored by GITenberg on GitHub), named <gutenberg-id>.txt.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { bookFromText, stripGutenberg } from '../src/books/split';

interface Spec {
  gid: number; id: string; title: string; author: string; blurb: string;
  start: RegExp; nth?: number; // the nth line matching `start` begins the book
  end?: RegExp; // the first line after the start matching `end` ends it
}

const BOOKS: Spec[] = [
  { gid: 84, id: 'frankenstein', title: 'Frankenstein', author: 'Mary Shelley', blurb: 'A scientist builds a living being, then runs from it.', start: /^Letter 1\s*$/ },
  { gid: 201, id: 'flatland', title: 'Flatland', author: 'Edwin A. Abbott', blurb: 'A square in a two-dimensional world discovers the third.', start: /^PART I:\s+THIS WORLD/, nth: 2 },
  { gid: 35, id: 'time-machine', title: 'The Time Machine', author: 'H. G. Wells', blurb: 'An inventor travels to the year 802,701.', start: /^I\s*$/ },
  { gid: 11, id: 'alice', title: "Alice's Adventures in Wonderland", author: 'Lewis Carroll', blurb: 'Logic games disguised as a children\'s book.', start: /^CHAPTER I\. Down the Rabbit-Hole/ },
  { gid: 1342, id: 'pride-and-prejudice', title: 'Pride and Prejudice', author: 'Jane Austen', blurb: 'The sharpest comedy of manners in English.', start: /^Chapter 1\s*$/ },
  { gid: 2680, id: 'meditations', title: 'Meditations', author: 'Marcus Aurelius', blurb: 'A Roman emperor\'s private notes on staying sane.', start: /^THE FIRST BOOK\s*$/, end: /^APPENDIX\s*$/ },
  { gid: 2500, id: 'siddhartha', title: 'Siddhartha', author: 'Hermann Hesse', blurb: 'A young man leaves everything to find out what matters.', start: /^THE SON OF THE BRAHMAN\s*$/ },
  { gid: 600, id: 'notes-from-underground', title: 'Notes from Underground', author: 'Fyodor Dostoevsky', blurb: 'A bitter, brilliant narrator argues against reason itself.', start: /^PART I\s*$/ },
  { gid: 1661, id: 'sherlock-holmes', title: 'The Adventures of Sherlock Holmes', author: 'Arthur Conan Doyle', blurb: 'Twelve cases. Watch the deductions.', start: /^ADVENTURE I\. A SCANDAL IN BOHEMIA/ },
  { gid: 4363, id: 'beyond-good-and-evil', title: 'Beyond Good and Evil', author: 'Friedrich Nietzsche', blurb: 'Philosophy in short, explosive aphorisms.', start: /^PREFACE\s*$/ },
];

const src = process.argv[2];
if (!src) { console.error('Usage: npx tsx scripts/make-books.ts <dir>'); process.exit(1); }
const out = join(__dirname, '../src/content/books');
mkdirSync(out, { recursive: true });

const catalogue: string[] = [];
for (const b of BOOKS) {
  const lines = stripGutenberg(readFileSync(join(src, `${b.gid}.txt`), 'utf8')).replace(/\r\n?/g, '\n').split('\n');
  let seen = 0, from = -1;
  for (let i = 0; i < lines.length; i++) if (b.start.test(lines[i]) && ++seen === (b.nth ?? 1)) { from = i; break; }
  if (from < 0) throw new Error(`${b.id}: start marker not found`);
  let to = lines.length;
  if (b.end) for (let i = from + 1; i < lines.length; i++) if (b.end.test(lines[i])) { to = i; break; }
  const book = bookFromText(lines.slice(from, to).join('\n'), b.title, b.author, b.id);
  const tooLong = book.bites.filter(x => x.split(/\s+/).length > 200).length;
  writeFileSync(join(out, `${b.id}.json`), JSON.stringify(book));
  catalogue.push(`  { id: '${b.id}', title: ${JSON.stringify(b.title)}, author: ${JSON.stringify(b.author)}, blurb: ${JSON.stringify(b.blurb)}, total: ${book.bites.length}, load: () => require('./${b.id}.json') },`);
  console.log(`${b.id}: ${book.bites.length} bites, ${book.chapters.length} chapters, ${tooLong} over 200 words`);
}

writeFileSync(join(out, 'index.ts'), `// Generated by scripts/make-books.ts. Do not edit by hand.
import type { BookData } from '../../books/types';

export interface BundledBook { id: string; title: string; author: string; blurb: string; total: number; load: () => BookData }

export const BUNDLED_BOOKS: BundledBook[] = [
${catalogue.join('\n')}
];
`);
